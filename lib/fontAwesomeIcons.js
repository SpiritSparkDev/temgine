export const getIconHtml = (iconName) => {
  if (typeof iconName === 'object' && iconName !== null) {
    const prefix = iconName.prefix || 'fas';
    return `<i class="${prefix} fa-${iconName.name}"></i>`;
  }
  return `<i class="fas fa-${iconName}"></i>`;
};
